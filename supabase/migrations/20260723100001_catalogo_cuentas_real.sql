-- 8. Verificaciones: el árbol debe quedar completo y sin huérfanos.
do $$
declare v_total int; v_huerfanas int; v_sin_subtipo int;
begin
  select count(*) into v_total from public.cuentas;
  select count(*) into v_huerfanas from public.cuentas c
   where public.fn_cuenta_codigo_padre(c.codigo) is not null and c.cuenta_padre_id is null;
  select count(*) into v_sin_subtipo from public.cuentas where subtipo_codigo is null;
  if v_huerfanas > 0 then
    raise exception 'Catálogo inconsistente: % cuentas sin padre resuelto.', v_huerfanas;
  end if;
  raise notice 'Catálogo cargado: % cuentas, 0 huérfanas, % sin subtipo.', v_total, v_sin_subtipo;
end $$;
