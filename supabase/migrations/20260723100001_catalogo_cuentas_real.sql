-- 6. El padre se deriva del código: se pone en '00' el último segmento no-cero.
create or replace function public.fn_cuenta_codigo_padre(p_codigo text)
returns text language plpgsql immutable as $$
declare v_parts text[]; i int;
begin
  v_parts := string_to_array(p_codigo, '-');
  for i in reverse array_length(v_parts,1)..1 loop
    if v_parts[i] <> '00' then
      if i = 1 then return null; end if;   -- raíz: no tiene padre
      v_parts[i] := '00';
      return array_to_string(v_parts, '-');
    end if;
  end loop;
  return null;
end $$;

update public.cuentas c
   set cuenta_padre_id = p.id
  from public.cuentas p
 where p.codigo = public.fn_cuenta_codigo_padre(c.codigo)
   and c.cuenta_padre_id is distinct from p.id;

